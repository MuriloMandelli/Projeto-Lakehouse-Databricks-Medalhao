"""Executa os notebooks do Databricks (notebooks/databricks/001 a 004) num Spark LOCAL.

Serve para testar a lógica antes de importar no Databricks. Faz as adaptações mínimas:
- o catálogo ``workspace.`` é removido (o Spark local tem só o catálogo padrão);
- ``CREATE VOLUME`` é ignorado e ``/Volumes/workspace/landing/dados`` vira ``data/landing``;
- ``dbutils.fs.ls`` e ``display`` são simulados.

Uso:
    uv run python tests/simular_databricks.py
"""

import json
import re
import shutil
import sys
from pathlib import Path
from types import SimpleNamespace

from delta import configure_spark_with_delta_pip
from pyspark.sql import DataFrame, SparkSession

RAIZ = Path(__file__).resolve().parents[1]
PASTA_NB = RAIZ / "notebooks" / "databricks"
PASTA_LANDING = RAIZ / "data" / "landing"
WAREHOUSE = Path("/tmp/lakehouse-simulado")
NOTEBOOKS = ["001_preparar_ambiente", "002_bronze", "003_silver", "004_gold"]


def criar_spark() -> SparkSession:
    shutil.rmtree(WAREHOUSE, ignore_errors=True)
    builder = (
        SparkSession.builder.master("local[*]")
        .config("spark.sql.extensions", "io.delta.sql.DeltaSparkSessionExtension")
        .config(
            "spark.sql.catalog.spark_catalog", "org.apache.spark.sql.delta.catalog.DeltaCatalog"
        )
        .config("spark.sql.warehouse.dir", str(WAREHOUSE))
        .config("spark.sql.shuffle.partitions", "4")
        .config("spark.ui.showConsoleProgress", "false")
    )
    spark = configure_spark_with_delta_pip(builder).getOrCreate()
    spark.sparkContext.setLogLevel("ERROR")
    return spark


def display(obj, n=20):
    if isinstance(obj, DataFrame):
        obj.show(n, truncate=False)
    else:
        for item in obj:
            print(item)


def dbutils_simulado():
    def ls(caminho):
        local = Path(caminho.replace("/Volumes/workspace/landing/dados", str(PASTA_LANDING)))
        return [
            SimpleNamespace(name=p.name, path=str(p), size=p.stat().st_size)
            for p in sorted(local.iterdir())
        ]

    return SimpleNamespace(fs=SimpleNamespace(ls=ls))


def gerar_chaves_identity(spark, tabela):
    """Imita o IDENTITY do Databricks: numera a coluna SK_ (1, 2, 3...) pela chave natural."""
    df = spark.table(tabela)
    sk = next(c for c in df.columns if c.startswith("SK_"))
    natural = next(c for c in df.columns if c.startswith("CODIGO_"))
    numerado = df.drop(sk).selectExpr(
        f"CAST(row_number() OVER (ORDER BY {natural}) AS BIGINT) AS {sk}", "*"
    )
    numerado.write.format("delta").mode("overwrite").saveAsTable(tabela)


def executar_sql(spark, texto):
    for comando in [c.strip() for c in texto.split(";") if c.strip()]:
        comando = comando.replace("workspace.", "")
        comando = re.sub(r"SHOW SCHEMAS IN \w+", "SHOW SCHEMAS", comando)
        # O Spark local não tem IDENTITY (recurso do Databricks): cria a coluna como BIGINT comum
        comando = comando.replace("GENERATED BY DEFAULT AS IDENTITY", "")
        if comando.upper().startswith("CREATE VOLUME"):
            print("(simulação) volume ignorado no Spark local")
            continue
        resultado = spark.sql(comando)
        if resultado.columns:
            resultado.show(20, truncate=False)
        destino = re.match(r"MERGE INTO (gold\.dim_\w+)", comando)
        if destino:
            gerar_chaves_identity(spark, destino.group(1))


def main() -> int:
    spark = criar_spark()
    DataFrame.display = lambda self, *a, **k: display(self)
    contexto = {"spark": spark, "dbutils": dbutils_simulado(), "display": display}
    for nome in NOTEBOOKS:
        print(f"\n{'=' * 30} {nome} {'=' * 30}")
        nb = json.loads((PASTA_NB / f"{nome}.ipynb").read_text(encoding="utf-8"))
        for i, celula in enumerate(c for c in nb["cells"] if c["cell_type"] == "code"):
            fonte = "".join(celula["source"])
            print(f"--- célula {i}: {fonte.splitlines()[0][:70]}")
            if fonte.startswith("%sql"):
                executar_sql(spark, fonte.removeprefix("%sql"))
            else:
                exec(
                    fonte.replace("/Volumes/workspace/landing/dados", str(PASTA_LANDING)), contexto
                )
    spark.stop()
    print("\nSIMULAÇÃO OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
